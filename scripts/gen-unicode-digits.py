#!/usr/bin/env python3
"""Writes include/grparse/unicode_digits.h, the Unicode decimal digit table.

Python's `re` matches `\\d` on str against Unicode general category Nd, the
decimal digits. The list marker port matches the same set, and the Markdown
export reads each digit's decimal value. This script derives both from
Python's own unicodedata so the table is never typed by hand.

The Unicode version is pinned: the script refuses to run on a Python whose
unicodedata is another version, because a different version adds digit
blocks and the header would change under the same name.

  python3 scripts/gen-unicode-digits.py           rewrite the header
  python3 scripts/gen-unicode-digits.py --check   exit 1 if it is stale

Python 3.14 ships Unicode 16.0.0. Only the standard library is used.
"""

import argparse
import pathlib
import sys
import unicodedata
from dataclasses import dataclass

UNICODE_VERSION = "16.0.0"
HEADER = pathlib.Path(__file__).resolve().parent.parent / "include/grparse/unicode_digits.h"


@dataclass(frozen=True)
class DecimalRun:
    """Consecutive Nd code points whose decimal values also step by one."""

    first: int
    last: int
    first_value: int


def decimal_runs() -> list[DecimalRun]:
    runs: list[DecimalRun] = []
    for code_point in range(sys.maxunicode + 1):
        char = chr(code_point)
        if unicodedata.category(char) != "Nd":
            continue
        value = unicodedata.decimal(char)
        if runs:
            last = runs[-1]
            if last.last + 1 == code_point and last.first_value + (code_point - last.first) == value:
                runs[-1] = DecimalRun(last.first, code_point, last.first_value)
                continue
        runs.append(DecimalRun(code_point, code_point, value))
    return runs


def render(runs: list[DecimalRun]) -> str:
    rows = "\n".join(
        f"    {{0x{run.first:05X}U, 0x{run.last:05X}U, {run.first_value}}},"
        f"  // {unicodedata.name(chr(run.first))}"
        for run in runs
    )
    digits = sum(run.last - run.first + 1 for run in runs)
    return f"""// Generated by scripts/gen-unicode-digits.py from Python's unicodedata,
// Unicode {UNICODE_VERSION}. Do not edit; rerun the script.
#pragma once

#include <array>
#include <optional>
#include <string_view>

namespace grparse::unicode {{

inline constexpr std::string_view kDecimalDigitUnicodeVersion = "{UNICODE_VERSION}";

// Code points first..last are general category Nd and their decimal values
// run up from first_value, one per code point.
struct DecimalRun {{
  char32_t first;
  char32_t last;
  int first_value;
}};

// {len(runs)} runs, {digits} code points, ascending.
inline constexpr std::array<DecimalRun, {len(runs)}> kDecimalRuns = {{{{
{rows}
}}}};

// The decimal value (0..9) of `c` when it is an Nd digit, as Python's
// unicodedata.decimal() gives it; nothing for any other code point.
constexpr std::optional<int> decimal_digit_value(char32_t c) {{
  size_t low = 0;
  size_t high = kDecimalRuns.size();
  while (low < high) {{
    const size_t mid = low + (high - low) / 2;
    if (c < kDecimalRuns[mid].first) {{
      high = mid;
    }} else if (c > kDecimalRuns[mid].last) {{
      low = mid + 1;
    }} else {{
      return kDecimalRuns[mid].first_value + static_cast<int>(c - kDecimalRuns[mid].first);
    }}
  }}
  return std::nullopt;
}}

}}  // namespace grparse::unicode
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the header differs from a fresh render")
    args = parser.parse_args()
    if unicodedata.unidata_version != UNICODE_VERSION:
        print(
            f"gen-unicode-digits: this Python has Unicode {unicodedata.unidata_version}, "
            f"the table is pinned to {UNICODE_VERSION}",
            file=sys.stderr,
        )
        return 2
    text = render(decimal_runs())
    if args.check:
        if HEADER.read_text(encoding="utf-8") != text:
            print(f"gen-unicode-digits: {HEADER} is stale; rerun without --check", file=sys.stderr)
            return 1
        print(f"gen-unicode-digits: {HEADER.name} matches Unicode {UNICODE_VERSION}")
        return 0
    HEADER.write_text(text, encoding="utf-8")
    print(f"gen-unicode-digits: wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
