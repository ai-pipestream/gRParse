#!/usr/bin/env python3
"""Rewrite ``manifest.json``: the pinned sha256 of every in-repo corpus fixture.

    uv run python eval/scorecard/fixtures/write_manifest.py

The manifest is what ``tests/test_corpus_integrity.py`` compares the working
tree against, so running this is the deliberate half of changing a fixture:
regenerate the bytes with ``build_all.sh`` first, run this second, and say in
the commit message why the bytes moved. Running it to silence a failing test
without a reason defeats the point of pinning them.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
MANIFEST = HERE / "manifest.json"
NOTE = (
    "Pinned digests of every in-repo scorecard corpus fixture. A fixture is "
    "generated by eval/scorecard/fixtures/build_all.sh or copied from a "
    "sibling repository's sample data; either way its bytes are part of the "
    "scored contract, so a change here has to be deliberate. Regenerate with "
    "eval/scorecard/fixtures/build_all.sh, then rewrite this file with "
    "eval/scorecard/fixtures/write_manifest.py and say in the commit why the "
    "bytes moved."
)


def digest_corpus(root: Path) -> dict[str, dict[str, object]]:
    """Every regular file directly under ``root``, by name, digest and size."""
    files: dict[str, dict[str, object]] = {}
    for path in sorted(root.iterdir()):
        if not path.is_file():
            continue
        data = path.read_bytes()
        files[path.name] = {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
    return files


def main(argv: list[str]) -> int:
    corpus_root = "tests/golden/corpus"
    root = REPO / corpus_root
    if not root.is_dir():
        print(f"no corpus directory at {root}", file=sys.stderr)
        return 2
    files = digest_corpus(root)
    manifest = {"note": NOTE, "corpus_root": corpus_root, "files": files}
    MANIFEST.write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    total = sum(int(entry["bytes"]) for entry in files.values())
    print(f"{MANIFEST}: {len(files)} fixtures, {total} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
